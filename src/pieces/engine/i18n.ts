export type EngineMessageKey = keyof (typeof messages)['en']

/** A problem's message in a locale, its names put in (a reason worded too). */
export function problemMessage(locale: string, each: Pick<Problem, 'code' | 'args'>): string {
  const vars: Record<string, string> = {}
  for (const [key, value] of Object.entries(each.args)) if (typeof value === 'string') vars[key] = value
  if (vars.reason !== undefined) {
    const prefix = each.code === 'form_malformed' ? 'xml.' : 'json.'
    const key = `${prefix}${vars.reason}`
    if (key in messages.en) vars.reason = t(messages, locale, key as EngineMessageKey)
  }
  return t(messages, locale, `problem.${each.code}` as EngineMessageKey, vars)
}

/** Why a file did not open, worded. */
export function openFailureKey(reason: string | undefined): EngineMessageKey {
  const key = `openFailed.${reason}`
  return key in messages.en ? (key as EngineMessageKey) : 'openFailed'
}
