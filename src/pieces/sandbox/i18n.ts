export type SandboxMessageKey = keyof (typeof messages)['en']

/** A failure code in words: the piece's own codes, then core's (the runner's and the host's). */
export function wordSandboxError(locale: string, code: string): string {
  const key = `error.${code}`
  if (key in messages.en) return t(messages, locale, key as SandboxMessageKey)
  return wordError(locale, code)
}
