export type ErrorsMessageKey = keyof (typeof messages)['en']

/** The key of a role's name. */
export const ROLE_KEYS = {
  sandbox: 'roleSandbox',
  development: 'roleDevelopment',
  staging: 'roleStaging',
  production: 'roleProduction'
} as const satisfies Record<string, ErrorsMessageKey>

/** The words for why a frame did not open; any other reason reads as `openFailed`. */
export function openFailureKey(reason: string | undefined): ErrorsMessageKey {
  const key = `openFailed.${reason}`
  return key in messages.en ? (key as ErrorsMessageKey) : 'openFailed'
}
